# String Creation
str1 = "Hello"
str2 = "Python"

print("First String:", str1)
print("Second String:", str2)

# String Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# String Repetition
repeat = str1 * 3
print("Repetition:", repeat)

# String Slicing
text = "Python Programming"

print("Original String:", text)
print("First 6 Characters:", text[0:6])
print("Characters from Index 7:", text[7:])
print("Last 11 Characters:", text[-11:])
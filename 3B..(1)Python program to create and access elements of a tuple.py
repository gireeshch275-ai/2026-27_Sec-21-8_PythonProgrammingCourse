# Create a tuple

numbers = (10, 20, 30, 40, 50)

# Display the tuple
print("Tuple Elements:", numbers)

# Access elements using indexing
print("First Element:", numbers[0])
print("Third Element:", numbers[2])
print("Last Element:", numbers[-1])

# Access elements using slicing
print("First Three Elements:", numbers[0:3])
print("Last Two Elements:", numbers[3:5])

# Traverse the tuple
print("Traversing the Tuple:")

for num in numbers:
    print(num)
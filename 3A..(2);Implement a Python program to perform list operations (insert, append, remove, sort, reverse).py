# List Operations

numbers = [40, 10, 30, 20]

print("Original List:", numbers)

# Insert an element
numbers.insert(1, 50)
print("After Insert:", numbers)

# Append an element
numbers.append(60)
print("After Append:", numbers)

# Remove an element
numbers.remove(30)
print("After Remove:", numbers)

# Sort the list
numbers.sort()
print("After Sort:", numbers)

# Reverse the list
numbers.reverse()
print("After Reverse:", numbers)